# Comparacion: operador de igualdad
print(2 == 2)
print(3 == 5)
print("si" == "sí")
print(2 == 2.0)
print(2 == -2)
# Igualdad: El operador igual a (==)
var = 0  # Asignando 0 a var
print(var == 0)

var = 1  # Asignando 1 a var
print(var == 0)
# Desigualdad: el operador no es igual a (!=)
var = 0  # Asignando 0 a var
print(var != 0)

var = 1  # Asignando 1 a var
print(var != 0)
