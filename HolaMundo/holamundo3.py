# Python como una calculadora
print("Esto es una suma de dos números: ", 2+2, end="\n\n")
# Operadores Básicos
# Exponenciación
print("Resultado de exponenciación: ", 2 ** 3)
print("Resultado de exponenciación: ", 2 ** 3., end="\n\n")
# Multiplicación
print("Resultado de multiplicación: ", 2 * 3)
print("Resultado de multiplicación: ", 2 * 3., end="\n\n")
# Division
print("Resultado de división: ", 6 / 3)
print("Resultado de división: ", 6 / 3., end="\n\n")
# División entera
print("Resultado de división entera: ", 6 // 3)
print("Resultado de división entera: ", 6 // 3., end="\n\n")
print("Resultado de división entera: ", 6 // 4)
print("Resultado de división entera: ", 6 // 4., end="\n\n")
print("Resultado de división entera: ", -6 // -4)
print("Resultado de división entera: ", 6 // -4., end="\n\n")
# Residuo (módulo)
print("Resultado del residuo: ", 14 % 4)
print("Resultado del residuo: ", 12 % 4.5, end="\n\n")
# Suma
print("Resultado de suma con estándar matemático: ", -4 + 4)
print("Resultado de suma con estándar matemático: ", -4 + 8., end="\n\n")
# El operador de resta, operadores unarios y binarios
print("Resultado de resta unarios y binarios: ", -4 - 4)
print("Resultado de resta unarios y binarios: ", -4 - 8)
print("Resultado de resta unarios y binarios: ", -1.1, end="\n\n")
